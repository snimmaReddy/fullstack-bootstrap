#!/usr/bin/env node
// Manage JSON schemas in schemas/. While the API runs in Development it picks up changes on save.
//
//   node scripts/schema.mjs new <name> field:type[!] ...     create schemas/<name>.json
//        types: string text email number integer boolean date enum ref   (! = required)
//        enum:  category:enum=hardware,software,service
//        ref:   supplier:ref=supplier   (id of a record in another schema)
//        e.g.   node scripts/schema.mjs new product name:string! price:number inStock:boolean
//        also creates api/Controllers/<Collection>Controller.cs (skip with --no-controller)
//   node scripts/schema.mjs controller <name>                add a controller for an existing schema
//   node scripts/schema.mjs list                             list schemas and their controllers
//   node scripts/schema.mjs delete <name> [--drop-data] [--yes] [--delete-controller]
//        removes the schema file; data is kept unless --drop-data (asks to confirm unless --yes);
//        asks before deleting the controller (or pass --delete-controller)
//
// To update a schema, edit its JSON file (hot-reloads). Controllers are C# code: restart the API after adding one.
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'schemas');
const META = 'schema.schema.json';
const TYPES = ['string', 'text', 'email', 'number', 'integer', 'boolean', 'date', 'enum', 'ref'];
const ALIASES = { bool: 'boolean', int: 'integer' };

const [cmd, ...rest] = process.argv.slice(2);
const flags = new Set(rest.filter((a) => a.startsWith('--')));
const args = rest.filter((a) => !a.startsWith('--'));

const die = (msg) => {
  console.error(msg);
  process.exit(1);
};
const fileOf = (name) => join(dir, `${name}.json`);
const controllersDir = join(root, 'api', 'Controllers');
const pascal = (s) => s.split('_').filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const controllerClass = (schema) => `${pascal(schema.collection ?? `${schema.name}s`)}Controller`;
const controllerFile = (schema) => join(controllersDir, `${controllerClass(schema)}.cs`);
const rel = (p) => p.slice(root.length + 1);
const capitalize = (s) => s[0].toUpperCase() + s.slice(1);

function readSchema(file) {
  return JSON.parse(readFileSync(join(dir, file), 'utf8'));
}

function controllerSource(schema) {
  const route = schema.collection ?? `${schema.name}s`;
  const cls = controllerClass(schema);
  const title = schema.title ?? pascal(route);
  return `using System.Text.Json;
using Api.Data;
using Microsoft.AspNetCore.Mvc;

namespace Api.Controllers;

/// <summary>
/// ${title} API. Fields and validation come from schemas/${schema.name}.json.
/// Generated by scripts/schema.mjs. It's regular code now: edit, remove or add actions as needed.
/// </summary>
[ApiController]
[Route("api/${route}")]
[Tags("${title}")]
public class ${cls}(Db db) : ControllerBase
{
    private const string Schema = "${schema.name}";

    /// <summary>List ${route}. Filters: ?field=value, ?field.lt=..., ?sort=-field, ?limit=, ?skip=, ?include=...</summary>
    [HttpGet]
    [ProducesResponseType<List<Record>>(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    public async Task<ActionResult<List<Record>>> GetAll()
    {
        var query = Query.FromRequest(Request);
        Response.Headers["X-Total-Count"] = (await db.Count(Schema, query)).ToString(); // total before paging
        return await db.List(Schema, query);
    }

    /// <summary>Get one ${schema.name} by id. ?include=... embeds related records.</summary>
    [HttpGet("{id}")]
    [ProducesResponseType<Record>(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<ActionResult<Record>> GetById(string id, [FromQuery] string? include)
    {
        var item = await db.Get(Schema, id, Query.SplitList(include));
        if (item is null) return NotFound();
        return item;
    }

    /// <summary>Create a ${schema.name}.</summary>
    [HttpPost]
    [ProducesResponseType<Record>(StatusCodes.Status201Created)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status409Conflict)]
    public async Task<ActionResult<Record>> Create([FromBody] JsonElement body)
    {
        var item = await db.Create(Schema, body);
        return CreatedAtAction(nameof(GetById), new { id = item["id"] }, item);
    }

    /// <summary>Replace a ${schema.name}: fields left out are cleared.</summary>
    [HttpPut("{id}")]
    [ProducesResponseType<Record>(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    [ProducesResponseType(StatusCodes.Status409Conflict)]
    public async Task<ActionResult<Record>> Update(string id, [FromBody] JsonElement body) =>
        await db.Update(Schema, id, body);

    /// <summary>Update only the given fields; null clears an optional field.</summary>
    [HttpPatch("{id}")]
    [ProducesResponseType<Record>(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    [ProducesResponseType(StatusCodes.Status409Conflict)]
    public async Task<ActionResult<Record>> Patch(string id, [FromBody] JsonElement body) =>
        await db.Patch(Schema, id, body);

    /// <summary>Delete a ${schema.name}. Refused (409) while other records reference it.</summary>
    [HttpDelete("{id}")]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    [ProducesResponseType(StatusCodes.Status409Conflict)]
    public async Task<IActionResult> Delete(string id)
    {
        await db.Delete(Schema, id);
        return NoContent();
    }

    // Add ${schema.name}-specific endpoints here, for example:
    // [HttpPost("{id}/archive")]
    // public async Task<ActionResult<Record>> Archive(string id) => await db.Patch(Schema, id, new { archived = true });
}
`;
}

function writeController(schema) {
  const file = controllerFile(schema);
  if (existsSync(file)) die(`${rel(file)} already exists.`);
  writeFileSync(file, controllerSource(schema));
  console.log(`created  ${rel(file)}  → /api/${schema.collection ?? `${schema.name}s`}`);
  console.log('Restart the API (or use `dotnet watch`) to serve the new controller.');
}

function cmdController() {
  const [name] = args;
  if (!name) die('Usage: schema.mjs controller <name>');
  if (!existsSync(fileOf(name))) die(`schemas/${name}.json not found. Create the schema first.`);
  writeController(readSchema(`${name}.json`));
}

function cmdNew() {
  const [name, ...specs] = args;
  if (!/^[a-z][a-z0-9]*$/.test(name ?? ''))
    die('Usage: schema.mjs new <name> field:type[!] ...   (name: lower-case letters/digits, e.g. product)');
  if (specs.length === 0) die('Give at least one field, e.g.  name:string!');
  if (existsSync(fileOf(name))) die(`schemas/${name}.json already exists. Edit it instead.`);

  const fields = {};
  for (const spec of specs) {
    const m = spec.match(/^([a-z][a-zA-Z0-9]*):([a-z]+)(!)?(?:=(.+))?$/);
    if (!m) die(`Bad field "${spec}". Format: name:type[!]  or  name:enum[!]=a,b,c  or  name:ref[!]=schema`);
    const [, field, rawType, required, values] = m;
    const type = ALIASES[rawType] ?? rawType;
    if (!TYPES.includes(type)) die(`Unknown type "${rawType}" for "${field}". Types: ${TYPES.join(', ')}`);
    if (['id', 'createdAt', 'updatedAt'].includes(field)) die(`"${field}" is added automatically.`);
    if (fields[field]) die(`Field "${field}" is listed twice.`);
    const def = { type };
    if (required) def.required = true;
    if (type === 'enum') {
      if (!values) die(`Enum field "${field}" needs values, e.g.  ${field}:enum=a,b,c`);
      def.values = values.split(',').map((v) => v.trim()).filter(Boolean);
    } else if (type === 'ref') {
      if (!/^[a-z][a-z0-9]*$/.test(values ?? '')) die(`Ref field "${field}" needs a target schema, e.g.  ${field}:ref=supplier`);
      def.ref = values;
    } else if (values) die(`Only enum and ref fields take "=..." ("${spec}").`);
    fields[field] = def;
  }

  const schema = { $schema: `./${META}`, name, title: capitalize(name) + 's', fields };
  const withController = !flags.has('--no-controller');
  if (withController && existsSync(controllerFile(schema))) die(`${rel(controllerFile(schema))} already exists.`);
  writeFileSync(fileOf(name), JSON.stringify(schema, null, 2) + '\n');
  console.log(`created  schemas/${name}.json`);
  console.log('Edit it to add labels, limits (maxLength, min, max), unique, defaults. The API reloads it on save.');
  if (withController) writeController(schema);
  else console.log(`No controller created. Add one later: node scripts/schema.mjs controller ${name}`);
}

function cmdList() {
  const files = readdirSync(dir).filter((f) => f.endsWith('.json') && f !== META).sort();
  if (files.length === 0) return console.log('No schemas yet. Create one: node scripts/schema.mjs new <name> field:type ...');
  const rows = [['NAME', 'COLLECTION', 'FIELDS', 'API', 'CONTROLLER']];
  for (const f of files) {
    try {
      const s = readSchema(f);
      const route = s.collection ?? `${s.name}s`;
      const hasController = existsSync(controllerFile(s));
      rows.push([s.name ?? '?', route, String(Object.keys(s.fields ?? {}).length),
        hasController ? `/api/${route}` : '(none)', hasController ? rel(controllerFile(s)) : '-']);
    } catch {
      rows.push([f.replace(/\.json$/, ''), '-', '-', '-', `schemas/${f} (invalid JSON)`]);
    }
  }
  const widths = rows[0].map((_, i) => Math.max(...rows.map((r) => r[i].length)));
  for (const r of rows) console.log(r.map((c, i) => c.padEnd(widths[i])).join('  ').trimEnd());
}

function apiConnectionString() {
  if (process.env.MONGO_URL) return process.env.MONGO_URL;
  const p = join(root, 'api', 'appsettings.Development.json');
  const conn = existsSync(p) && JSON.parse(readFileSync(p, 'utf8')).Mongo?.ConnectionString;
  if (!conn) die('No MongoDB connection string. Run scripts/db.sh init-users, or set MONGO_URL.');
  return conn;
}

async function cmdDelete() {
  const [name] = args;
  if (!name) die('Usage: schema.mjs delete <name> [--drop-data] [--yes]');
  if (!existsSync(fileOf(name))) die(`schemas/${name}.json not found.`);

  let schema = { name };
  try {
    schema = readSchema(`${name}.json`);
  } catch {
    /* invalid JSON: fall back to the default collection name */
  }
  const collection = schema.collection ?? `${name}s`;

  const drop = flags.has('--drop-data');
  if (drop && !flags.has('--yes')) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const answer = await rl.question(
      `This permanently deletes every document in "${collection}". Type the collection name to confirm: `);
    rl.close();
    if (answer.trim() !== collection) die('Cancelled. Nothing was deleted.');
  }

  // The controller is code you may have edited, so only delete it when asked.
  const ctrl = controllerFile(schema);
  let deleteController = flags.has('--delete-controller');
  if (existsSync(ctrl) && !deleteController && process.stdin.isTTY) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    deleteController = /^y(es)?$/i.test((await rl.question(`Also delete ${rel(ctrl)}? [y/N] `)).trim());
    rl.close();
  }

  // Remove the file first so a running API stops serving it before the data goes.
  unlinkSync(fileOf(name));
  console.log(`deleted  schemas/${name}.json`);
  if (existsSync(ctrl)) {
    if (deleteController) {
      unlinkSync(ctrl);
      console.log(`deleted  ${rel(ctrl)}  (restart the API)`);
    } else {
      console.log(`kept     ${rel(ctrl)}  (it now returns "Unknown schema" until the schema is back; delete it if unneeded)`);
    }
  }

  if (!drop) {
    console.log(`Data in "${collection}" was kept. Drop it later with --drop-data, or from Compass as admin.`);
    return;
  }
  const r = spawnSync('mongosh', [apiConnectionString(), '--quiet', '--eval',
    `print(db.getCollection(${JSON.stringify(collection)}).drop())`], { encoding: 'utf8' });
  if (r.status !== 0) die(`Could not drop "${collection}": ${(r.stderr || r.stdout).trim()}`);
  console.log(r.stdout.trim() === 'true' ? `dropped  collection ${collection}` : `collection ${collection} did not exist`);
}

switch (cmd) {
  case 'new': cmdNew(); break;
  case 'controller': cmdController(); break;
  case 'list': cmdList(); break;
  case 'delete': await cmdDelete(); break;
  default:
    die('Usage: node scripts/schema.mjs new <name> field:type[!] ... [--no-controller] | controller <name> | list | delete <name> [--drop-data] [--yes] [--delete-controller]');
}
